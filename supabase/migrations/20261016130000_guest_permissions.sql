-- PATCH-380. The owner decides what guests may do; the owner can remove guests.
--
-- WHY. The owner asked that a guest may not upload or use AI "unless the admin
-- gives them permission". PATCH-379 made guests safe but blunt: AI and uploads
-- are refused outright. This adds the two switches that lift those refusals, and
-- the two operations that make guest access revocable -- remove a person, and
-- delete a link together with the people who joined through it.
--
-- WHAT IS NOT HERE. No storage policy changes: a guest NEVER writes to Storage
-- directly (PATCH-358's `guest_no_storage_*` restrictive policies stay exactly as
-- they are). A guest upload goes through the server route, which uses the admin
-- client -- so the database keeps refusing the direct write while the route can
-- still serve the guest the owner allowed.
--
-- THE ACTIVITY TABLE IS SERVER-ONLY. RLS is enabled with NO policies at all, and
-- every privilege is revoked from `anon` and `authenticated`: nobody but the
-- service role can read or write it. PATCH-358's guest write guard is a ONE-TIME
-- loop over the tables that existed when it ran, so it does not cover a table
-- added later -- this table needs no guest policy precisely because it is not
-- reachable by anyone but the server.
--
-- DO NOT APPLY from a coding session -- the owner runs this in the Supabase SQL
-- editor. Depends on `public.share_links` (20261013140000).

BEGIN;

-- 1. The two switches. BOTH OFF: a guest keeps exactly the access PATCH-379 left
-- them until the owner says otherwise.
ALTER TABLE public.boards ADD COLUMN IF NOT EXISTS guest_uploads_allowed boolean NOT NULL DEFAULT false;
ALTER TABLE public.boards ADD COLUMN IF NOT EXISTS guest_ai_allowed boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.boards.guest_uploads_allowed IS
  'PATCH-380. When true, a guest may upload images and PDFs through the server route. Storage still refuses a guest direct write.';
COMMENT ON COLUMN public.boards.guest_ai_allowed IS
  'PATCH-380. When true, a guest may use Board AI, charged to this board owner''s plan. Answer-only: a guest never gets board-change proposals.';

-- 2. The guard. Only the OWNER changes what guests may do -- not an admin, not a
-- workspace manager (the Share modal is reachable by admins, and this is the
-- owner's own money and board). Service role (no auth.uid()) passes.
CREATE OR REPLACE FUNCTION public.guard_board_guest_permissions()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN NEW;  -- service role: unchanged
  END IF;

  IF (NEW.guest_uploads_allowed IS DISTINCT FROM OLD.guest_uploads_allowed
      OR NEW.guest_ai_allowed IS DISTINCT FROM OLD.guest_ai_allowed)
     AND OLD.user_id IS DISTINCT FROM auth.uid() THEN
    RAISE EXCEPTION 'Only the board owner can change what guests may do'
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$function$;

-- Trigger-only: nobody needs EXECUTE.
REVOKE EXECUTE ON FUNCTION public.guard_board_guest_permissions() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS boards_guard_guest_permissions ON public.boards;
CREATE TRIGGER boards_guard_guest_permissions
  BEFORE UPDATE ON public.boards
  FOR EACH ROW
  EXECUTE FUNCTION public.guard_board_guest_permissions();

-- 3. WHO JOINED THROUGH WHICH LINK. Existing rows stay NULL -- they joined before
-- this column existed, and guessing which link they used would be a lie.
ALTER TABLE public.board_collaborators ADD COLUMN IF NOT EXISTS joined_via_link_id uuid;

-- The FK is added separately and guarded, so a re-run does not fail on a
-- constraint that already exists. ON DELETE SET NULL: deleting a link on its own
-- must never remove anyone -- that is the explicit "also remove" path's job.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'board_collaborators_joined_via_link_id_fkey'
  ) THEN
    ALTER TABLE public.board_collaborators
      ADD CONSTRAINT board_collaborators_joined_via_link_id_fkey
      FOREIGN KEY (joined_via_link_id) REFERENCES public.share_links(id) ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS board_collaborators_joined_via_link_idx
  ON public.board_collaborators (joined_via_link_id);

-- 4. The activity ledger: one row per allowed guest AI call or upload, so the
-- caps are countable. Server-only (see the header).
CREATE TABLE IF NOT EXISTS public.guest_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id uuid NOT NULL REFERENCES public.boards(id) ON DELETE CASCADE,
  user_id uuid NOT NULL,
  kind text NOT NULL CHECK (kind IN ('ai', 'upload')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS guest_activity_lookup_idx
  ON public.guest_activity (board_id, user_id, kind, created_at);

ALTER TABLE public.guest_activity ENABLE ROW LEVEL SECURITY;

-- NO POLICIES, deliberately: with RLS on and none declared, every role except the
-- service role sees nothing and may write nothing. The REVOKE below is the belt
-- to that pair of braces.
DROP POLICY IF EXISTS guest_activity_none ON public.guest_activity;

REVOKE ALL ON public.guest_activity FROM PUBLIC, anon, authenticated;

-- 5. SELF-CHECK. A missing column, trigger, table or revoke rolls the whole
-- transaction back rather than leaving a half-applied permission model.
DO $$
DECLARE
  missing text;
BEGIN
  SELECT string_agg(want, ', ') INTO missing
    FROM unnest(ARRAY['guest_uploads_allowed', 'guest_ai_allowed']) AS want
   WHERE NOT EXISTS (
     SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'boards' AND column_name = want
   );
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'PATCH-380: boards is missing column(s): %', missing;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = 'board_collaborators' AND column_name = 'joined_via_link_id'
  ) THEN
    RAISE EXCEPTION 'PATCH-380: board_collaborators.joined_via_link_id is missing';
  END IF;

  IF to_regprocedure('public.guard_board_guest_permissions()') IS NULL THEN
    RAISE EXCEPTION 'PATCH-380: public.guard_board_guest_permissions() is missing';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'boards_guard_guest_permissions') THEN
    RAISE EXCEPTION 'PATCH-380: boards_guard_guest_permissions trigger is missing';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'board_collaborators_joined_via_link_id_fkey') THEN
    RAISE EXCEPTION 'PATCH-380: the joined_via_link_id foreign key is missing';
  END IF;

  IF to_regclass('public.guest_activity') IS NULL THEN
    RAISE EXCEPTION 'PATCH-380: public.guest_activity is missing';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_class WHERE relname = 'guest_activity' AND relrowsecurity = true
  ) THEN
    RAISE EXCEPTION 'PATCH-380: public.guest_activity must have RLS enabled';
  END IF;

  -- Nobody but the service role: `authenticated` must hold NO privilege at all.
  IF has_table_privilege('authenticated', 'public.guest_activity', 'SELECT')
     OR has_table_privilege('authenticated', 'public.guest_activity', 'INSERT')
     OR has_table_privilege('authenticated', 'public.guest_activity', 'UPDATE')
     OR has_table_privilege('authenticated', 'public.guest_activity', 'DELETE') THEN
    RAISE EXCEPTION 'PATCH-380: authenticated must hold no privilege on public.guest_activity';
  END IF;
END $$;

COMMIT;
